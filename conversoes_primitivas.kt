fun main (args: Array<String>){
    val x = 120
    val y = x.toString()
    val z = x.toByte()
    val w = x.toFloat()
    
    val texto = "90"
    val numero = texto.toInt()
    val r = numero + 4
    
    println("$x")
    println("$y")
    println("$z")
    println("$w")
    println(texto)
    println(numero)
    println(r)
}
