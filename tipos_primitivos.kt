fun main (args: Array<String>){
    val c: Char = 'M'
    val i: Int = 120
    val f: Float = 120F
    val s: String = "texto"
    val d: Double = 2103.1203
    val l: Long = 12_1203_120335_5L
    //funciona sem o citado
    
    println("$c")
    println("$i")
    println("$f")
    println(s)
    println("$d")
    println("$l")
    
}
